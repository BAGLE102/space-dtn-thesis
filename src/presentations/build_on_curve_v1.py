def graph(s,x0,y0,w,h,t0,t1,vmax,ticks,vt,series,unit='秒',ylab='占用（包）'):
    sx=w/(t1-t0);sy=h/vmax;yb=y0+h
    for v in vt:
        hline(s,x0,yb-v*sy,x0+w,'E3E3E3',.5);tb(s,x0-.45,yb-v*sy-.13,.38,.26,str(v),12,MUT)
    tb(s,x0-.6,y0-.42,1.4,.28,ylab,12,MUT)
    axis(s,x0,x0+w,yb,[(t,x0+(t-t0)*sx) for t in ticks],unit)
    for pts,col,wd,dash in series:
        poly(s,[(x0+(float(t)-t0)*sx,yb-float(v)*sy) for t,v in pts],col,wd,dash)

